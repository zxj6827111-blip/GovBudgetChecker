"""108 检查点 → 必要子场景 → 金标证据的映射规格（只读分析用）。

约定：
- 每个子场景的 components 是该子要求的“证据来源”。一个 component 可以是：
  * check   ：整项 GS 检查的四态结论；
  * items   ：GS 检查内按 item label 正则筛出的子项；
  * fu      ：自由发现的真值类；exhaustive=True 表示该类金标要求穷尽扫描，缺席可记 pass；
  * none    ：没有对应金标证据（政策排除、暂缓、或尚未覆盖）。
- 主证据（primary）只分配给一个检查点；其他检查点如复用同一证据，标 shared_with，
  其计数不得与主项相加（coverage_inventory.csv 的 count_scope 列会注明）。
"""


def C(check, label=None, note=None):
    return {"kind": "check", "check": check, "label_regex": label, "note_regex": note}


def I(check, label, note=None):
    return {"kind": "items", "check": check, "label_regex": label, "note_regex": note}


def NS(check, positive, negative):
    return {"kind": "note_scan", "check": check, "positive_regex": positive, "negative_regex": negative}


def F(cls, exhaustive=False):
    return {"kind": "fu", "cls": cls, "exhaustive": exhaustive}


def FR(cls, ref_sub, exhaustive=False):
    return {"kind": "fu_ref", "cls": cls, "ref_sub": ref_sub, "exhaustive": exhaustive}


def N(reason):
    return {"kind": "none", "reason": reason}


def S(sub_id, requirement, components, mapping, confidence, note="", shared_with="", mode="all"):
    return {
        "sub_id": sub_id,
        "requirement": requirement,
        "components": components,
        "mapping": mapping,
        "confidence": confidence,
        "note": note,
        "shared_with": shared_with,
        "mode": mode,
    }


